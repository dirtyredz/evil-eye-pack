'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { copy } = require('../copy.cjs');
const { output } = require('../../data_io/path_guard.cjs');
const { manifest, verify } = require('../snapshot.cjs');
test('independent copy, complete manifest, protected paths, overlaps and junctions', t => {
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'world-trial-'));
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  const source=path.join(dir,'source'), job=path.join(dir,'job'), dest=path.join(job,'copy');
  fs.mkdirSync(source);fs.writeFileSync(path.join(source,'level.dat'),'world');
  const before=manifest(source);copy(source,dest,job);
  verify(dest,before);fs.writeFileSync(path.join(dest,'level.dat'),'changed');verify(source,before);
  assert.throws(()=>verify(dest,before),/Manifest mismatch/);
  assert.throws(()=>copy(source,path.join(source,'child'),dir),/Overlapping/);
  assert.throws(()=>output(dest,job,[source,job]),/Protected/);
  assert.throws(()=>output(source,job),/below job/);
  const link=path.join(job,'link');fs.symlinkSync(source,link,'junction');
  assert.throws(()=>copy(link,path.join(job,'bad'),job),/Symlink/);
  assert.throws(()=>output(path.join(link,'new'),job),/Symlink/);
});
